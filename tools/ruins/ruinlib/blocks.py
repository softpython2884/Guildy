"""
Block states of the target Minecraft version (data/blocks.json, generated by gen_block_data.py): parsing,
validation, canonical form ("minecraft:id[prop=value,...]" with every property, sorted) and rotation / mirroring.
"""
import json
import os

DATA = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")

with open(os.path.join(DATA, "blocks.json"), encoding="utf-8") as _f:
	_RAW = json.load(_f)
VERSION = _RAW["version"]
BLOCKS = _RAW["blocks"]  # id -> {"p": {prop: [values]}, "d": {prop: default}}

DATA_VERSION = 5023  # SharedConstants.WORLD_VERSION of Minecraft 26.3

# Blocks that must never appear in a ruin template.
FORBIDDEN = {"minecraft:command_block", "minecraft:chain_command_block", "minecraft:repeating_command_block",
	"minecraft:barrier", "minecraft:jigsaw", "minecraft:light", "minecraft:structure_void", "minecraft:bedrock",
	"minecraft:end_portal", "minecraft:end_gateway", "minecraft:nether_portal", "minecraft:test_block",
	"minecraft:test_instance_block", "minecraft:moving_piston", "minecraft:reinforced_deepslate"}


class BlockError(ValueError):
	pass


def full_id(block_id):
	return block_id if ":" in block_id else "minecraft:" + block_id


def parse(state):
	"""'stone_brick_stairs[facing=north]' -> ('minecraft:stone_brick_stairs', {'facing': 'north'})."""
	state = state.strip()
	props = {}
	if "[" in state:
		block_id, rest = state.split("[", 1)
		rest = rest.rstrip("]")
		for part in filter(None, rest.split(",")):
			key, _, value = part.partition("=")
			props[key.strip()] = value.strip()
	else:
		block_id = state
	return full_id(block_id.strip()), props


def fmt(block_id, props):
	if not props:
		return block_id
	return block_id + "[" + ",".join(f"{k}={props[k]}" for k in sorted(props)) + "]"


def exists(block_id):
	return full_id(block_id) in BLOCKS


def properties(block_id):
	return BLOCKS.get(full_id(block_id), {}).get("p", {})


def canon(state, strict=True):
	"""Canonical state string with defaults filled in. Raises BlockError on an unknown id / property / value."""
	block_id, props = parse(state)
	entry = BLOCKS.get(block_id)
	if entry is None:
		raise BlockError(f"unknown block '{block_id}'")
	defs = entry.get("p", {})
	result = dict(entry.get("d", {}))
	for key, value in props.items():
		if key not in defs:
			if strict:
				raise BlockError(f"{block_id} has no property '{key}' (valid: {', '.join(defs) or 'none'})")
			continue
		if value not in defs[key]:
			if strict:
				raise BlockError(f"{block_id}: '{key}' cannot be '{value}' (valid: {', '.join(defs[key])})")
			continue
		result[key] = value
	return fmt(block_id, result)


def block_of(state):
	return parse(state)[0]


def prop(state, key, default=None):
	return parse(state)[1].get(key, default)


def with_props(state, **changes):
	block_id, props = parse(state)
	props.update({k: str(v).lower() if isinstance(v, bool) else str(v) for k, v in changes.items()})
	return canon(fmt(block_id, props))


# ---------------------------------------------------------------------------------------- rotation / mirror

HORIZONTAL = ["north", "east", "south", "west"]
_ROT_FACE = {d: i for i, d in enumerate(HORIZONTAL)}


def rotate_dir(direction, quarter_turns):
	"""Clockwise rotation seen from above (north -> east -> south -> west)."""
	if direction in _ROT_FACE:
		return HORIZONTAL[(_ROT_FACE[direction] + quarter_turns) % 4]
	return direction


def mirror_dir(direction, axis):
	"""axis 'x': mirror across the YZ plane (east <-> west); axis 'z': north <-> south."""
	if axis == "x":
		return {"east": "west", "west": "east"}.get(direction, direction)
	return {"north": "south", "south": "north"}.get(direction, direction)


def rotate(state, quarter_turns):
	"""Rotates a block state clockwise by 90 degrees * quarter_turns (like Rotation.CLOCKWISE_90)."""
	quarter_turns %= 4
	if quarter_turns == 0:
		return state
	block_id, props = parse(state)
	out = dict(props)
	for key, value in props.items():
		if key in ("facing", "horizontal_facing") and value in _ROT_FACE:
			out[key] = rotate_dir(value, quarter_turns)
		elif key == "axis" and value in ("x", "z") and quarter_turns % 2 == 1:
			out[key] = "z" if value == "x" else "x"
		elif key == "rotation":
			out[key] = str((int(value) + 4 * quarter_turns) % 16)
		elif key == "orientation":  # jigsaw / crafter: "<front>_<top>"
			front, top = value.split("_")
			out[key] = rotate_dir(front, quarter_turns) + "_" + rotate_dir(top, quarter_turns)
		elif key in _ROT_FACE:
			out.pop(key, None)
	for key, value in props.items():
		if key in _ROT_FACE:
			out[rotate_dir(key, quarter_turns)] = value
	if block_id.endswith("_rail") or block_id == "minecraft:rail":
		pass  # rails are not used in ruins
	return fmt(block_id, out)


def mirror(state, axis):
	"""Mirrors a state (axis 'x' swaps east/west, 'z' swaps north/south), like Mirror.FRONT_BACK / LEFT_RIGHT."""
	block_id, props = parse(state)
	out = dict(props)
	for key, value in props.items():
		if key in ("facing",) and value in _ROT_FACE:
			out[key] = mirror_dir(value, axis)
		elif key == "rotation":
			r = int(value)
			out[key] = str((16 - r) % 16) if axis == "x" else str((8 - r) % 16)
		elif key == "shape" and "stairs" in block_id:
			swap = {"inner_left": "inner_right", "inner_right": "inner_left",
				"outer_left": "outer_right", "outer_right": "outer_left"}
			out[key] = swap.get(value, value)
		elif key == "hinge":
			out[key] = "right" if value == "left" else "left"
		elif key in _ROT_FACE:
			out.pop(key, None)
	for key, value in props.items():
		if key in _ROT_FACE:
			out[mirror_dir(key, axis)] = value
	return fmt(block_id, out)
