	@Test
	void uniqueArmorsHaveTheirWornLook() throws Exception {
		Path root = assets().getParent().getParent();
		Set<String> definitions = new TreeSet<>();
		for (Path file : files("equipment", ".json")) {
			definitions.add(name(file, ".json"));
		}
		assertEquals(new TreeSet<>(UniqueEquipment.ASSETS.keySet()), definitions, "one equipment asset per unique armor, nothing stale");
		for (var entry : UniqueEquipment.ASSETS.entrySet()) {
			String asset = entry.getKey();
			String slot = entry.getValue();
			JsonObject layers = json(root.resolve(UniqueEquipment.definitionPath(asset))).getAsJsonObject("layers");
			JsonArray main = layers.getAsJsonArray(UniqueEquipment.layer(slot));
			assertNotNull(main, asset + ": layer " + UniqueEquipment.layer(slot));
			assertEquals(1, main.size(), asset + ": a single layer");
			JsonObject layer = main.get(0).getAsJsonObject();
			assertEquals("guildy:" + asset, layer.get("texture").getAsString(), asset + ": its own texture");
			assertTrue(!layer.has("dyeable"), asset + ": the drawing replaces the dyed leather");
			assertTrue(layers.has("humanoid_baby"), asset + ": baby mobs keep the vanilla look (other layout)");
			Path texture = root.resolve(UniqueEquipment.texturePath(asset, slot));
			try (InputStream in = Files.newInputStream(texture)) {
				byte[] head = in.readNBytes(24);
				assertEquals(24, head.length, texture + ": truncated");
				assertEquals("IHDR", new String(head, 12, 4), texture + ": not a PNG");
				assertEquals(64, ByteBuffer.wrap(head, 16, 4).getInt(), texture + ": 64 px wide");
				assertEquals(32, ByteBuffer.wrap(head, 20, 4).getInt(), texture + ": 32 px high");
			}
			// Equipment textures are not atlas sprites: Minecraft would ignore an animation.
			assertTrue(!Files.exists(texture.resolveSibling(texture.getFileName() + ".mcmeta")), asset + ": no animation");
		}
		try (Stream<Path> stream = Files.walk(assets().resolve("textures/entity/equipment"))) {
			Set<String> expected = new HashSet<>();
			UniqueEquipment.ASSETS.forEach((asset, slot) -> expected.add(UniqueEquipment.texturePath(asset, slot)));
			List<String> stale = stream.filter(Files::isRegularFile)
					.map(file -> root.relativize(file).toString().replace(java.io.File.separatorChar, '/'))
					.filter(file -> !expected.contains(file))
					.toList();
			assertTrue(stale.isEmpty(), "unused equipment textures: " + stale);
		}
	}
