package dev.guildy.unique;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.guildy.scroll.ScrollConfig;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.net.URL;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The optional resource pack (assets/guildy, generated by tools/gen_textures.py): every item definition resolves to
 * existing models, every model to existing textures and known vanilla parents, every texture is a 16 px wide sprite
 * whose animation (.mcmeta) is valid, nothing is orphaned, and the grimoire has one model per default spell scroll.
 */
class ResourcePackTest {
	private static final Set<String> VANILLA_PARENTS = Set.of("minecraft:item/generated", "minecraft:item/handheld",
			"minecraft:item/handheld_mace", "minecraft:item/bow", "minecraft:item/crossbow");

	private static Path assets() throws Exception {
		URL url = ResourcePackTest.class.getResource("/assets/guildy/items");
		assertNotNull(url, "assets/guildy/items on the test classpath");
		return Path.of(url.toURI()).getParent();
	}

	private static List<Path> files(String dir, String suffix) throws Exception {
		try (Stream<Path> stream = Files.list(assets().resolve(dir))) {
			return stream.filter(p -> p.getFileName().toString().endsWith(suffix)).sorted().toList();
		}
	}

	private static String name(Path file, String suffix) {
		String value = file.getFileName().toString();
		return value.substring(0, value.length() - suffix.length());
	}

	private static JsonObject json(Path file) throws IOException {
		return JsonParser.parseString(Files.readString(file)).getAsJsonObject();
	}

	/** guildy:item/x -> x (null for another namespace). */
	private static String local(String id) {
		return id.startsWith("guildy:item/") ? id.substring("guildy:item/".length()) : null;
	}

	/** Every model referenced in an item definition tree ("model" strings at any depth). */
	private static void modelRefs(JsonElement element, List<String> out) {
		if (element.isJsonObject()) {
			for (var entry : element.getAsJsonObject().entrySet()) {
				if (entry.getKey().equals("model") && entry.getValue().isJsonPrimitive()) {
					out.add(entry.getValue().getAsString());
				} else {
					modelRefs(entry.getValue(), out);
				}
			}
		} else if (element.isJsonArray()) {
			for (JsonElement child : element.getAsJsonArray()) {
				modelRefs(child, out);
			}
		}
	}

	@Test
	void itemDefinitionsResolveToModels() throws Exception {
		List<String> missing = new ArrayList<>();
		for (Path file : files("items", ".json")) {
			JsonObject root = json(file);
			assertTrue(root.has("model"), file + ": no model");
			List<String> refs = new ArrayList<>();
			modelRefs(root.get("model"), refs);
			assertTrue(!refs.isEmpty(), file + ": no model reference");
			for (String ref : refs) {
				String model = local(ref);
				assertNotNull(model, file + ": model outside guildy:item/: " + ref);
				if (!Files.isRegularFile(assets().resolve("models/item/" + model + ".json"))) {
					missing.add(file.getFileName() + " -> " + ref);
				}
			}
		}
		assertTrue(missing.isEmpty(), "missing models: " + missing);
	}

	@Test
	void modelsResolveToTexturesAndKnownParents() throws Exception {
		List<String> problems = new ArrayList<>();
		for (Path file : files("models/item", ".json")) {
			JsonObject model = json(file);
			String parent = model.get("parent").getAsString();
			if (local(parent) != null) {
				if (!Files.isRegularFile(assets().resolve("models/item/" + local(parent) + ".json"))) {
					problems.add(file.getFileName() + ": parent " + parent);
				}
			} else if (!VANILLA_PARENTS.contains(parent)) {
				problems.add(file.getFileName() + ": unknown vanilla parent " + parent);
			}
			for (var texture : model.getAsJsonObject("textures").entrySet()) {
				String id = texture.getValue().getAsString();
				if (!id.startsWith("guildy:item/")
						|| !Files.isRegularFile(assets().resolve("textures/item/" + id.substring("guildy:item/".length()) + ".png"))) {
					problems.add(file.getFileName() + ": texture " + id);
				}
			}
		}
		assertTrue(problems.isEmpty(), "broken models: " + problems);
	}

	@Test
	void texturesAreValidSprites() throws Exception {
		List<String> problems = new ArrayList<>();
		for (Path file : files("textures/item", ".png")) {
			byte[] head;
			try (InputStream in = Files.newInputStream(file)) {
				head = in.readNBytes(24);
			}
			assertEquals(24, head.length, file + ": truncated");
			assertEquals("IHDR", new String(head, 12, 4), file + ": not a PNG");
			int width = ByteBuffer.wrap(head, 16, 4).getInt();
			int height = ByteBuffer.wrap(head, 20, 4).getInt();
			int frames = height / width;
			if (width != 16 || height % width != 0) {
				problems.add(file.getFileName() + ": " + width + "x" + height);
				continue;
			}
			Path meta = file.resolveSibling(file.getFileName() + ".mcmeta");
			if (frames > 1 && !Files.isRegularFile(meta)) {
				problems.add(file.getFileName() + ": " + frames + " frames without .mcmeta");
			}
			if (Files.isRegularFile(meta)) {
				JsonObject animation = json(meta).getAsJsonObject("animation");
				if (animation == null || frames < 2) {
					problems.add(meta.getFileName() + ": no animation or a single frame");
					continue;
				}
				if (animation.has("frametime") && animation.get("frametime").getAsInt() < 1) {
					problems.add(meta.getFileName() + ": frametime");
				}
				if (animation.has("frames")) {
					JsonArray order = animation.getAsJsonArray("frames");
					for (JsonElement entry : order) {
						int index = entry.isJsonObject() ? entry.getAsJsonObject().get("index").getAsInt() : entry.getAsInt();
						boolean badTime = entry.isJsonObject() && entry.getAsJsonObject().has("time")
								&& entry.getAsJsonObject().get("time").getAsInt() < 1;
						if (index < 0 || index >= frames || badTime) {
							problems.add(meta.getFileName() + ": frame " + entry);
						}
					}
				}
			}
		}
		for (Path meta : files("textures/item", ".png.mcmeta")) {
			if (!Files.isRegularFile(meta.resolveSibling(name(meta, ".mcmeta")))) {
				problems.add(meta.getFileName() + ": no texture");
			}
		}
		assertTrue(problems.isEmpty(), "invalid textures: " + problems);
	}

	@Test
	void nothingIsOrphaned() throws Exception {
		Set<String> usedModels = new HashSet<>();
		for (Path file : files("items", ".json")) {
			List<String> refs = new ArrayList<>();
			modelRefs(json(file).get("model"), refs);
			refs.forEach(ref -> usedModels.add(local(ref)));
		}
		Set<String> usedTextures = new HashSet<>();
		for (Path file : files("models/item", ".json")) {
			JsonObject model = json(file);
			if (local(model.get("parent").getAsString()) != null) {
				usedModels.add(local(model.get("parent").getAsString()));
			}
			model.getAsJsonObject("textures").entrySet().forEach(e -> usedTextures.add(local(e.getValue().getAsString())));
		}
		Set<String> orphans = new TreeSet<>();
		for (Path file : files("models/item", ".json")) {
			if (!usedModels.contains(name(file, ".json"))) {
				orphans.add("model " + file.getFileName());
			}
		}
		for (Path file : files("textures/item", ".png")) {
			if (!usedTextures.contains(name(file, ".png"))) {
				orphans.add("texture " + file.getFileName());
			}
		}
		assertTrue(orphans.isEmpty(), "unused assets (stale outputs of tools/gen_textures.py?): " + orphans);
	}

	@Test
	void grimoireSelectsOneModelPerScroll() throws Exception {
		JsonObject model = json(assets().resolve("items/grimoire.json")).getAsJsonObject("model");
		assertEquals("minecraft:select", model.get("type").getAsString());
		assertEquals("minecraft:custom_model_data", model.get("property").getAsString());
		assertEquals(0, model.has("index") ? model.get("index").getAsInt() : 0);
		assertEquals("guildy:item/grimoire", model.getAsJsonObject("fallback").get("model").getAsString(), "dormant book");
		Set<String> cases = new HashSet<>();
		for (JsonElement entry : model.getAsJsonArray("cases")) {
			JsonObject value = entry.getAsJsonObject();
			assertTrue(cases.add(value.get("when").getAsString()), "duplicate case " + value.get("when"));
			assertEquals("guildy:item/grimoire_" + value.get("when").getAsString(),
					value.getAsJsonObject("model").get("model").getAsString());
		}
		ScrollConfig cfg = new ScrollConfig();
		cfg.rebuild(id -> true);
		Set<String> spells = new HashSet<>();
		for (ScrollConfig.ScrollDef def : cfg.usable()) {
			spells.add(def.id);
		}
		assertEquals(spells, cases, "one grimoire model per default spell scroll");
	}

	@Test
	void cursedGrimoireSelectsOneModelPerScroll() throws Exception {
		JsonObject model = json(assets().resolve("items/grimoire_maudit.json")).getAsJsonObject("model");
		assertEquals("minecraft:select", model.get("type").getAsString());
		assertEquals("minecraft:custom_model_data", model.get("property").getAsString());
		assertEquals(0, model.has("index") ? model.get("index").getAsInt() : 0);
		assertEquals("guildy:item/grimoire_maudit", model.getAsJsonObject("fallback").get("model").getAsString(), "dormant cursed tome");
		Set<String> cases = new HashSet<>();
		for (JsonElement entry : model.getAsJsonArray("cases")) {
			JsonObject value = entry.getAsJsonObject();
			String spell = value.get("when").getAsString();
			assertTrue(cases.add(spell), "duplicate case " + spell);
			assertEquals("guildy:item/grimoire_maudit_" + spell, value.getAsJsonObject("model").get("model").getAsString());
			assertTrue(Files.isRegularFile(assets().resolve("textures/item/grimoire_maudit_" + spell + ".png.mcmeta")), spell + ": animated");
		}
		ScrollConfig cfg = new ScrollConfig();
		cfg.rebuild(id -> true);
		Set<String> spells = new HashSet<>();
		for (ScrollConfig.ScrollDef def : cfg.usable()) {
			spells.add(def.id);
		}
		assertEquals(spells, cases, "one cursed grimoire model per default spell scroll");
		assertEquals("grimoire_maudit", cfg.cursedGrimoire.model, "the item_model of the config");
	}

	@Test
	void incantationScrollAndCrossbowStatesShipped() throws Exception {
		assertTrue(Files.isRegularFile(assets().resolve("items/parchemin_incantation.json")));
		assertTrue(Files.isRegularFile(assets().resolve("textures/item/parchemin_incantation.png")));
		// The cursed incantation scroll: its own animated sprite, model and item definition.
		assertTrue(Files.isRegularFile(assets().resolve("textures/item/parchemin_incantation_maudit.png")));
		assertTrue(Files.isRegularFile(assets().resolve("textures/item/parchemin_incantation_maudit.png.mcmeta")), "animated");
		assertEquals("guildy:item/parchemin_incantation_maudit",
				json(assets().resolve("items/parchemin_incantation_maudit.json")).getAsJsonObject("model").get("model").getAsString());
		assertEquals("guildy:item/parchemin_incantation_maudit", json(assets().resolve("models/item/parchemin_incantation_maudit.json"))
				.getAsJsonObject("textures").get("layer0").getAsString());
		JsonObject crossbow = json(assets().resolve("items/arbalete_du_traqueur.json")).getAsJsonObject("model");
		assertEquals("minecraft:charge_type", crossbow.get("property").getAsString(), "vanilla crossbow states");
		List<String> refs = new ArrayList<>();
		modelRefs(crossbow, refs);
		assertEquals(Set.of("standby", "pulling_0", "pulling_1", "pulling_2", "arrow", "firework"), refs.stream()
				.map(ref -> local(ref).replace("arbalete_du_traqueur", "").replaceFirst("^_", ""))
				.map(state -> state.isEmpty() ? "standby" : state).collect(java.util.stream.Collectors.toSet()));
	}
}
